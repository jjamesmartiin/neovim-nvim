  set noswapfile
  set mouse=a
  set number relativenumber
  set tabstop=2 shiftwidth=2 expandtab
  set listchars=tab:»·,trail:·
  set noincsearch
  set ignorecase smartcase
  set backspace=indent,eol,start
  set hidden
  set updatetime=300
  set shortmess+=c
]]
